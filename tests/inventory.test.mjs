import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {chromium} from 'playwright';
import {startServer} from '../server.js';
import {buildWorkbook} from '../src/xlsx.js';

test('inventory sidebar imports and adjusts stock; picker and grade guidance preserve desktop layout',{timeout:60000},async t=>{
  const dataDir=await mkdtemp(path.join(tmpdir(),'jackery-stock-ui-'));
  const app=await startServer({dataDir,demo:true,catalogPath:'catalogs/jackery-eu-20261030.json'});
  let browser;
  t.after(async()=>{await browser?.close();await app.close();await rm(dataDir,{recursive:true,force:true});});
  browser=await chromium.launch({headless:true,executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe'});
  const page=await browser.newPage({viewport:{width:1366,height:768}});
  page.setDefaultTimeout(5000);
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(app.baseUrl);
  await page.locator('#username').fill('admin');
  await page.locator('#password').fill('JackeryAdmin!2026');
  await page.locator('#login-form button').click();
  await page.locator('#inventory-nav').click();
  await page.locator('#stock-detail .stock-value').waitFor();
  assert.equal(await page.locator('#stock-detail .stock-value').innerText(),'0');
  const catalog=await page.evaluate(async()=>await (await fetch('/api/catalog')).json());
  const model=catalog.models.find(x=>x.catalogKey==='e1000v2-costdown');
  assert.ok(model);
  const material=await page.evaluate(async id=>(await (await fetch('/api/models/'+id+'/bom')).json()).items[0],model.id);
  const list=async (kind,file)=>{
    await page.locator(`[data-stock-section="${kind}"]`).click();
    await page.locator('#stock-file').setInputFiles(file);
    await page.locator('#stock-upload button').click();
    await page.locator('#stock-confirm').click();
    await page.locator('#stock-preview [role=status]').waitFor();
    assert.match(await page.locator('#stock-preview').innerText(),/Rows updated · 1/);
  };
  await list('open',{name:'stock.csv',mimeType:'text/csv',buffer:Buffer.from('sku,quantity\n'+material.sku+',2')});
  const adjustment=buildWorkbook([{name:'Stock',columns:[{key:'sku'},{key:'delta'}],rows:[{sku:material.sku,delta:-3}]}]);
  await list('adjust',{name:'adjustment.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:adjustment});
  await page.locator('[data-stock-section=query]').click();
  await page.locator('#stock-q').fill(material.sku);
  await page.locator('#stock-search button').click();
  await page.locator('#stock-detail .danger').waitFor();
  assert.equal(await page.locator('#stock-detail .danger').innerText(),'-1');
  await page.locator('#stock-view-history').click();
  await page.locator('#stock-clear').waitFor();
  assert.match(await page.locator('.stock-filter').innerText(),new RegExp(material.sku));
  await page.locator('#records-nav').click();
  await page.locator('#new-record').click();
  await page.locator('#sn').fill('STOCK-GRADE-UI');
  await page.locator('#modelId').selectOption(String(model.id));
  for(const viewport of [{width:1366,height:768},{width:1536,height:864}]){
    await page.setViewportSize(viewport);
    const group=page.locator('.outcome-grid');
    const before=await group.boundingBox();
    await page.locator('#grade-criteria-button').click();
    assert.equal(await page.locator('#grade-criteria').isVisible(),true);
    assert.match(await page.locator('#grade-criteria').innerText(),/at most 1 wear mark/);
    assert.match(await page.locator('#grade-criteria').innerText(),/at most 5 wear marks/);
    assert.deepEqual(await group.boundingBox(),before);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#grade-criteria').isVisible(),false);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  }
  await page.locator('#open-bom').click();
  const stock=page.locator('#bom-results tr').filter({hasText:material.sku}).locator('.bom-stock');
  await stock.waitFor();
  assert.match(await stock.innerText(),/-1/);
  assert.equal(await page.locator('#bom-dialog').evaluate(el=>el.scrollWidth>el.clientWidth),false);
  await page.locator('#bom-language').click();
  await page.waitForFunction(()=>document.documentElement.lang==='zh');
  await stock.waitFor();
  assert.match(await stock.innerText(),/-1/);
  assert.match(await page.locator('#bom-dialog thead').innerText(),/当前库存/);
  assert.deepEqual(errors,[]);
});

test('material management imports OMS names and retries a previously rejected stock file',{timeout:60000},async t=>{
  const dataDir=await mkdtemp(path.join(tmpdir(),'jackery-material-ui-'));
  const app=await startServer({dataDir,demo:true});
  let browser;
  t.after(async()=>{await browser?.close();await app.close();await rm(dataDir,{recursive:true,force:true});});
  browser=await chromium.launch({headless:true,executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe'});
  const page=await browser.newPage();
  page.setDefaultTimeout(5000);
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(app.baseUrl);
  await page.locator('#username').fill('admin');
  await page.locator('#password').fill('JackeryAdmin!2026');
  await page.locator('#login-form button').click();
  await page.locator('#inventory-nav').click();
  await page.locator('[data-stock-section=open]').click();
  const sku='WAREHOUSE-NEW-001';
  await page.locator('#stock-file').setInputFiles({name:'stock.csv',mimeType:'text/csv',buffer:Buffer.from('sku,quantity\n'+sku+',9')});
  await page.locator('#stock-upload button').click();
  await page.locator('#stock-materials-link').click();
  await page.locator('.material-import[open]').waitFor();
  const xlsx=buildWorkbook([{name:'OMS',columns:[
    {key:'sku',label:'SKU'},{key:'name',label:'Product Name/产品名称'},
    ...Array.from({length:24},(_,i)=>({key:'extra'+i})),{key:'quantity',label:'Total Stock/总库存'},
  ],rows:[{sku,name:'仓库新零件',quantity:88}]}]);
  await page.locator('#material-file').setInputFiles({name:'oms.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:xlsx});
  await page.locator('#material-upload button').click();
  await page.locator('#material-preview').getByText('仓库新零件',{exact:true}).waitFor();
  await page.locator('#material-confirm').click();
  await page.locator('#material-preview [role=status]').waitFor();
  assert.match(await page.locator('#material-preview').innerText(),/Created rows · 1/);
  await page.locator('#material-q').fill(sku);
  await page.locator('#material-search button').click();
  const row=page.locator('#material-list tr').filter({hasText:sku});
  await row.getByRole('button',{name:'Disable',exact:true}).click();
  await row.getByRole('button',{name:'Enable',exact:true}).click();
  await row.getByRole('button',{name:'Disable',exact:true}).waitFor();
  await page.locator('[data-stock-section=open]').click();
  await page.locator('#stock-upload button').click();
  await page.locator('#stock-confirm').click();
  await page.locator('#stock-preview [role=status]').waitFor();
  assert.match(await page.locator('#stock-preview').innerText(),/Rows updated · 1/);
  await page.locator('[data-stock-section=query]').click();
  await page.locator('#stock-q').fill(sku);
  await page.locator('#stock-search button').click();
  await page.locator('#stock-detail').getByText(sku,{exact:true}).waitFor();
  assert.equal(await page.locator('#stock-detail .stock-value').innerText(),'9');
  assert.deepEqual(errors,[]);
});
